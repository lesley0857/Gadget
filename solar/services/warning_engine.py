# ======================================================================

def _validate_inverter(
    result: Dict[str, Any],
    load_result: Dict[str, Any],
    voltage_result: Dict[str, Any],
) -> List[Dict[str, Any]]:

    warnings = []

    requirement = result.get(
        "requirement",
        {},
    )

    selected = result.get(
        "selected",
        {},
    )

    if not isinstance(
        requirement,
        dict,
    ):
        requirement = {}

    if not isinstance(
        selected,
        dict,
    ):
        selected = {}

    required_power = _decimal(
        _first(
            requirement,
            "required_power_w",
            "minimum_power_w",
            "inverter_power_w",
            default=ZERO,
        )
    )

    selected_power = _decimal(
        _first(
            selected,
            "power_w",
            "rated_power_w",
            "capacity_w",
            "continuous_power_w",
            default=ZERO,
        )
    )

    if (
        required_power > ZERO
        and
        selected_power > ZERO
        and
        selected_power < required_power
    ):
        warnings.append(
            _warning(
                code="INVERTER_UNDERSIZED",
                severity=SEVERITY_CRITICAL,
                message=(
                    "Selected inverter continuous power is "
                    "below the calculated requirement."
                ),
                category="inverter",
                source=ENGINE_NAME,
                recommendation=(
                    "Select an inverter with sufficient "
                    "continuous output capacity."
                ),
            )
        )

    selected_surge = _decimal(
        _first(
            selected,
            "surge_power_w",
            "surge_capacity_w",
            "peak_power_w",
            default=ZERO,
        )
    )

    load_calculations = load_result.get(
        "calculations",
        {}
    )

    if not isinstance(
        load_calculations,
        dict,
    ):
        load_calculations = {}

    required_surge = _decimal(
        _first(
            load_calculations,
            "surge_peak_load_w",
            "peak_design_load_w",
            default=_first(
                load_result,
                "surge_watts",
                "surge_load_w",
                default=ZERO,
            ),
        )
    )

    if (
        required_surge > ZERO
        and
        selected_surge > ZERO
        and
        selected_surge < required_surge
    ):
        warnings.append(
            _warning(
                code="INVERTER_SURGE_INADEQUATE",
                severity=SEVERITY_ERROR,
                message=(
                    "The selected inverter surge capability is "
                    "below the calculated design surge demand."
                ),
                category="inverter",
                source=ENGINE_NAME,
                recommendation=(
                    "Verify motor/compressor starting demand "
                    "and inverter surge specifications."
                ),
            )
        )

    system_voltage = _first(
        voltage_result,
        "system_voltage",
        "selected_voltage",
        default=None,
    )

    inverter_voltage = _first(
        selected,
        "battery_voltage",
        "dc_voltage",
        "input_voltage",
        "nominal_voltage",
        default=None,
    )

    if (
        system_voltage is not None
        and
        inverter_voltage is not None
    ):
        system = _decimal(
            system_voltage
        )
        inverter = _decimal(
            inverter_voltage
        )

        if (
            system > ZERO
            and
            inverter > ZERO
            and
            system != inverter
        ):
            warnings.append(
                _warning(
                    code="INVERTER_DC_VOLTAGE_MISMATCH",
                    severity=SEVERITY_CRITICAL,
                    message=(
                        "The selected inverter DC voltage does "
                        "not match the selected system voltage."
                    ),
                    category="inverter",
                    source=ENGINE_NAME,
                    recommendation=(
                        "Verify inverter DC input voltage and "
                        "battery-system voltage compatibility."
                    ),
                )
            )

    return warnings


