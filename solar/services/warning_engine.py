# ======================================================================
# CROSS-ENGINE VALIDATION
# ======================================================================

def _validate_cross_engine(
    results: Dict[str, Any],
) -> List[Dict[str, Any]]:

    warnings = []

    voltage_result = results.get(
        "voltage_result",
        {}
    )

    battery_result = results.get(
        "battery_result",
        {}
    )

    panel_result = results.get(
        "panel_result",
        {}
    )

    controller_result = results.get(
        "controller_result",
        {}
    )

    inverter_result = results.get(
        "inverter_result",
        {}
    )

    system_voltage = _positive(
        _first(
            voltage_result,
            "system_voltage",
            "selected_voltage",
            "recommended_system_voltage",
            default=None,
        )
    )

    if system_voltage:

        battery_system_voltage = _positive(
            _nested(
                battery_result,
                "requirement",
                "system_voltage",
                "nominal_system_voltage",
                default=None,
            )
        )

        if (
            battery_system_voltage
            and
            battery_system_voltage != system_voltage
        ):
            warnings.append(
                _warning(
                    code="VOLTAGE_BATTERY_ENGINE_MISMATCH",
                    severity=SEVERITY_CRITICAL,
                    message=(
                        "The system voltage selected by the "
                        "System Voltage Engine does not match "
                        "the voltage used by the Battery Engine."
                    ),
                    category="integration",
                    source=ENGINE_NAME,
                    recommendation=(
                        "Use one consistent system-voltage value "
                        "throughout the design pipeline."
                    ),
                )
            )

        inverter_system_voltage = _positive(
            _nested(
                inverter_result,
                "requirement",
                "system_voltage",
                "battery_voltage",
                "dc_voltage",
                default=None,
            )
        )

        if (
            inverter_system_voltage
            and
            inverter_system_voltage != system_voltage
        ):
            warnings.append(
                _warning(
                    code="VOLTAGE_INVERTER_ENGINE_MISMATCH",
                    severity=SEVERITY_CRITICAL,
                    message=(
                        "The inverter requirements use a system "
                        "voltage different from the selected "
                        "system voltage."
                    ),
                    category="integration",
                    source=ENGINE_NAME,
                    recommendation=(
                        "Verify the inverter DC-voltage "
                        "architecture."
                    ),
                )
            )

    # --------------------------------------------------------------
    # PV → CONTROLLER
    # --------------------------------------------------------------

    panel_power = _positive(
        _nested(
            panel_result,
            "selected",
            "array_power",
            "array_power_w",
            default=None,
        )
    )

    controller_required_power = _positive(
        _nested(
            controller_result,
            "requirement",
            "minimum_pv_power",
            "minimum_controller_power",
            default=None,
        )
    )

    if (
        panel_power
        and
        controller_required_power
        and
        panel_power < controller_required_power
    ):
        warnings.append(
            _warning(
                code="PV_CONTROLLER_POWER_MISMATCH",
                severity=SEVERITY_ERROR,
                message=(
                    "The selected PV array does not satisfy "
                    "the charge-controller engineering requirement."
                ),
                category="integration",
                source=ENGINE_NAME,
                recommendation=(
                    "Review PV array size and controller capacity."
                ),
            )
        )

    return warnings


# ======================================================================
# DEDUPLICATION
# ======================================================================

def _deduplicate(
    warnings: Iterable[Dict[str, Any]],
) -> List[Dict[str, Any]]:
    """Remove duplicate warnings while preserving order."""

    result = []
    seen = set()

    for item in warnings:

        key = (
            item.get("code"),
            item.get("severity"),
            item.get("message"),
        )

        if key in seen:
            continue

        seen.add(key)
        result.append(item)

    return result


# ======================================================================
# SUMMARY
# ======================================================================

def _build_summary(
    warnings: List[Dict[str, Any]],
) -> Dict[str, Any]:

    summary = {
        "total": len(warnings),
        "critical": 0,
        "error": 0,
        "warning": 0,
        "advisory": 0,
        "info": 0,
    }

    for item in warnings:

        severity = item.get(
            "severity",
            SEVERITY_WARNING,
        )

        if severity in summary:
            summary[severity] += 1

    summary["blocking"] = (
        summary["critical"]
        +
        summary["error"]
    )

    summary["requires_attention"] = (
        summary["blocking"]
        +
        summary["warning"]
    )

    return summary


# ======================================================================
# FINAL STATUS
# ======================================================================

def _final_status(
    summary: Dict[str, Any],
) -> str:

    if summary["critical"] > 0:
        return "critical"

    if summary["error"] > 0:
        return "not_ready"

    if summary["warning"] > 0:
        return "review"

    if summary["advisory"] > 0:
        return "acceptable_with_advisories"

    return "ready"


# ======================================================================
# MAIN ENGINE
# ======================================================================

def validate_design(
    *,
    load_result: Dict[str, Any],
    voltage_result: Dict[str, Any],
    battery_result: Dict[str, Any],
    panel_result: Dict[str, Any],
    controller_result: Dict[str, Any],
    inverter_result: Dict[str, Any],
    protection_result: Dict[str, Any],
    cable_result: Dict[str, Any],
    accessory_result: Dict[str, Any],
    boq_result: Dict[str, Any],
    pricing_result: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Perform final design warnings and cross-engine validation.

    All preceding engine results are passed explicitly.

    Returns a stable result dictionary suitable for:

        - views
        - templates
        - JSON
        - SolarDesign JSONField
        - PDF/report generation
        - final design orchestration
    """

    results = {
        "load_result": load_result,
        "voltage_result": voltage_result,
        "battery_result": battery_result,
        "panel_result": panel_result,
        "controller_result": controller_result,
        "inverter_result": inverter_result,
        "protection_result": protection_result,
        "cable_result": cable_result,
        "accessory_result": accessory_result,
        "boq_result": boq_result,
        "pricing_result": pricing_result,
    }

    warnings: List[Dict[str, Any]] = []

    # --------------------------------------------------------------
    # UPSTREAM WARNINGS
    # --------------------------------------------------------------

    warnings.extend(
        _collect_upstream_warnings(
            results
        )
    )

    # --------------------------------------------------------------
    # PIPELINE VALIDATION
    # --------------------------------------------------------------

    warnings.extend(
        _validate_stage_results(
            results
        )
    )

    # --------------------------------------------------------------
    # ENGINE-SPECIFIC VALIDATION
    # --------------------------------------------------------------

    warnings.extend(
        _validate_load(
            load_result
        )
    )

    warnings.extend(
        _validate_voltage(
            voltage_result,
            battery_result,
        )
    )

    warnings.extend(
        _validate_battery(
            battery_result
        )
    )

    warnings.extend(
        _validate_panel(
            panel_result,
            controller_result,
        )
    )

    warnings.extend(
        _validate_controller(
            controller_result
        )
    )

    warnings.extend(
        _validate_inverter(
            inverter_result,
            load_result,
            voltage_result,
        )
    )

    warnings.extend(
        _validate_protection(
            protection_result
        )
    )

    warnings.extend(
        _validate_cables(
            cable_result
        )
    )

    warnings.extend(
        _validate_boq(
            boq_result
        )
    )

    warnings.extend(
        _validate_pricing(
            pricing_result
        )
    )

    # --------------------------------------------------------------
    # CROSS-ENGINE VALIDATION
    # --------------------------------------------------------------

    warnings.extend(
        _validate_cross_engine(
            results
        )
    )

    # --------------------------------------------------------------
    # DEDUPLICATE
    # --------------------------------------------------------------

    warnings = _deduplicate(
        warnings
    )

    # --------------------------------------------------------------
    # SUMMARY
    # --------------------------------------------------------------

    summary = _build_summary(
        warnings
    )

    status = _final_status(
        summary
    )

    # --------------------------------------------------------------
    # FINAL RESULT
    # --------------------------------------------------------------

    success = status not in {
        "critical",
        "not_ready",
    }

    return {
        "success": success,
        "status": status,

        "ready_for_final_design": (
            status == "ready"
            or
            status == "acceptable_with_advisories"
        ),

        "summary": summary,

        "warnings": warnings,

        "critical_warnings": [
            item
            for item in warnings
            if item["severity"]
            == SEVERITY_CRITICAL
        ],

        "errors": [
            item
            for item in warnings
            if item["severity"]
            == SEVERITY_ERROR
        ],

        "review_warnings": [
            item
            for item in warnings
            if item["severity"]
            == SEVERITY_WARNING
        ],

        "advisories": [
            item
            for item in warnings
            if item["severity"]
            == SEVERITY_ADVISORY
        ],

        "messages": [
            (
                "Final engineering validation completed."
            ),
            (
                f"Design validation status: {status}."
            ),
        ],

        "message": (
            "Design validation completed successfully."
            if success
            else
            "Design validation identified issues "
            "that require attention."
        ),

        "engine": ENGINE_NAME,
        "engine_version": ENGINE_VERSION,
    }


